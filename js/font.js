export const FONTS = { small: SMALL, large: LARGE };

const colCache = new Map();
function glyphCols(font, ch) {
  const key = font.h + ch;
  if (colCache.has(key)) return colCache.get(key);
  const rows = (font.g[ch] || font.g['?']).split('/');
  const cols = [];
  for (let x = 0; x < font.w; x++) {
    let bits = 0;
    for (let y = 0; y < font.h; y++) if (rows[y][x] === '#') bits |= 1 << y;
    cols.push(bits);
  }
  colCache.set(key, cols);
  return cols;
}

// 'auto' picks the big font when the light has enough rows to show it
export const resolveFont = (font, rows) => (font === 'small' || font === 'large' ? font : rows >= 7 ? 'large' : 'small');

// Text -> array of column bitmaps (1 blank column between letters)
const textCache = new Map();
export function textColumns(text, fontName) {
  const key = fontName + '\u0000' + text;
  if (textCache.has(key)) return textCache.get(key);
  const font = FONTS[fontName];
  const out = [];
  for (const ch of String(text || '').toUpperCase().slice(0, 64)) out.push(...glyphCols(font, ch), 0);
  if (!out.length) out.push(0);
  if (textCache.size > 100) textCache.clear();
  textCache.set(key, out);
  return out;
}
