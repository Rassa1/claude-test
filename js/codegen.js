// Generates a complete Arduino/PlatformIO sketch for ESP32 + FastLED that
// reproduces the simulated animation exactly (same math as animations.js).
import { ANIMS, DIRS } from './animations.js';

const wrap = (arr, per = 20, indent = '  ') => {
  const lines = [];
  for (let k = 0; k < arr.length; k += per) lines.push(indent + arr.slice(k, k + per).join(', '));
  return lines.join(',\n');
};

function describe(s) {
  const d = ANIMS[s.type];
  const bits = [d.name];
  if (d.uses.includes('dir')) bits.push(DIRS[s.dir]);
  if (d.uses.includes('color')) bits.push(`rgb(${s.color.join(',')})`);
  bits.push(`${s.duration}s`);
  return bits.join(' · ');
}

export function generateSketch(matrix, layout, steps) {
  const n = layout.leds.length;
  const U = layout.leds.map((l) => l.qu);
  const V = layout.leds.map((l) => l.qv);
  const durMs = steps.map((s) => Math.max(1, Math.round(s.duration * 1000)));
  const total = durMs.reduce((a, b) => a + b, 0) || 1;
  const rowsDesc = matrix.rows.map((r, i) => ` *   row ${i + 1}: ${r.count} LEDs, offset ${(+r.offset).toFixed(1)} mm`).join('\n');

  const stepFns = steps.map((s, k) => {
    const def = ANIMS[s.type] || ANIMS.off;
    return `// Step ${k + 1}: ${describe(s)}
static CRGB step${k}(int i, float u, float v, float t) {
  (void)i; (void)u; (void)v; (void)t;
  const float BR = ${(+s.brightness).toFixed(3)}f;
  (void)BR;
  ${def.cpp(s)}
}`;
  }).join('\n\n');

  const dispatch = steps.map((_, k) => `    case ${k}: return step${k}(i, u, v, t);`).join('\n');

  return `/*
 * LED Taillight animation – generated by Taillight Studio
 * ---------------------------------------------------------
 * Board:   ESP32 (any dev board)
 * Library: FastLED  (Arduino IDE: Sketch > Include Library > Manage Libraries > "FastLED")
 *
 * Wiring:
 *   LED DIN  -> GPIO ${matrix.dataPin} (through a 330 Ω resistor; a 74AHCT125 level shifter is recommended)
 *   LED 5V   -> 5V supply (NOT the ESP32 3V3 pin)   LED GND -> supply GND + ESP32 GND
 *   In a car use a 12V -> 5V buck converter rated for the current below.
 *
 * Matrix: ${n} LEDs, ${matrix.rows.length} rows, ${matrix.ledsPerMeter} LEDs/m, ${matrix.wiring} wiring starting ${matrix.start}
${rowsDesc}
 *
 * Animation loop (${(total / 1000).toFixed(2)} s):
${steps.map((s, k) => ` *   ${k + 1}. ${describe(s)}`).join('\n')}
 */

#include <FastLED.h>
#include <math.h>

#define DATA_PIN        ${matrix.dataPin}
#define NUM_LEDS        ${n}
#define LED_TYPE        ${matrix.ledType}
#define COLOR_ORDER     ${matrix.colorOrder}
#define MAX_MILLIAMPS   ${matrix.maxMilliamps}   // FastLED will limit brightness to stay under this
#define FRAME_MS        10                // ~100 fps

CRGB leds[NUM_LEDS];

// Normalised LED positions (0..255) in wiring order: U = left->right, V = top->bottom
const uint8_t LED_U[NUM_LEDS] = {
${wrap(U)}
};
const uint8_t LED_V[NUM_LEDS] = {
${wrap(V)}
};

static const float TWO_PI_F = 6.28318530718f;
static inline float clamp01(float x) { return x < 0.0f ? 0.0f : (x > 1.0f ? 1.0f : x); }
static inline float fractf(float x) { return x - floorf(x); }
static inline CRGB shade(uint8_t r, uint8_t g, uint8_t b, float k) {
  k = clamp01(k);
  return CRGB((uint8_t)(r * k + 0.5f), (uint8_t)(g * k + 0.5f), (uint8_t)(b * k + 0.5f));
}
static inline CRGB mix2(uint8_t r1, uint8_t g1, uint8_t b1, uint8_t r2, uint8_t g2, uint8_t b2, float m, float k) {
  k = clamp01(k);
  float r = (r1 + (r2 - r1) * m) * k, g = (g1 + (g2 - g1) * m) * k, b = (b1 + (b2 - b1) * m) * k;
  return CRGB((uint8_t)(clamp01(r / 255.0f) * 255.0f + 0.5f), (uint8_t)(clamp01(g / 255.0f) * 255.0f + 0.5f), (uint8_t)(clamp01(b / 255.0f) * 255.0f + 0.5f));
}
static inline CRGB hueColor(float h, float k) {
  float r = clamp01(fabsf(h * 6.0f - 3.0f) - 1.0f);
  float g = clamp01(2.0f - fabsf(h * 6.0f - 2.0f));
  float b = clamp01(2.0f - fabsf(h * 6.0f - 4.0f));
  return shade((uint8_t)(r * 255.0f + 0.5f), (uint8_t)(g * 255.0f + 0.5f), (uint8_t)(b * 255.0f + 0.5f), k);
}
static inline uint32_t hash32(uint32_t a, uint32_t b) {
  uint32_t h = (a * 0x9E3779B1u) ^ ((b + 1u) * 0x85EBCA6Bu);
  h ^= h >> 15;
  h *= 0x2C1B3C6Du;
  h ^= h >> 12;
  return h;
}

${stepFns}

static const uint32_t STEP_MS[] = { ${durMs.join(', ')} };
static const int NUM_STEPS = ${steps.length};
static const uint32_t LOOP_MS = ${total};

static CRGB renderPixel(int step, int i, float u, float v, float t) {
  switch (step) {
${dispatch}
    default: return CRGB::Black;
  }
}

void setup() {
  FastLED.addLeds<LED_TYPE, DATA_PIN, COLOR_ORDER>(leds, NUM_LEDS);
  FastLED.setMaxPowerInVoltsAndMilliamps(5, MAX_MILLIAMPS);
  FastLED.setBrightness(255);
  FastLED.clear(true);
}

void loop() {
  static uint32_t lastFrame = 0;
  uint32_t now = millis();
  if (now - lastFrame < FRAME_MS) return;
  lastFrame = now;

  uint32_t tc = now % LOOP_MS;
  int step = 0;
  uint32_t start = 0;
  while (step < NUM_STEPS - 1 && tc >= start + STEP_MS[step]) { start += STEP_MS[step]; step++; }
  float t = (tc - start) / 1000.0f;

  for (int i = 0; i < NUM_LEDS; i++) {
    leds[i] = renderPixel(step, i, LED_U[i] / 255.0f, LED_V[i] / 255.0f, t);
  }
  FastLED.show();
}
`;
}
